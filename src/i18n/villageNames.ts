export function englishVillageName(name: number): string {
  return EN_ROOTS[Math.floor(name / NAME_ENDINGS)] + EN_ENDINGS[name % NAME_ENDINGS]
}

export function russianVillageName(name: number): string {
  const names = RU_NAMES[Math.floor(name / NAME_ENDINGS)]
  return names[(name % NAME_ENDINGS) % names.length]
}
